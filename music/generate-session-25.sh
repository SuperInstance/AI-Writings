"""SongForge Session 25 — ACE-Step local generation with Ollama-generated lyrics.

Generates indie folk covers of Casey's "Molding Memories" using:
1. ACE-Step 1.5 turbo on RTX 4050 (local, 6GB VRAM)
2. Lyrics generated by phi3 and qwen2.5 via Ollama
3. Original Casey lyrics for comparison

All tracks saved to /home/eileen/projects/covers/experiments_v5/
"""
