def main():
    print("=" * 60)
    print("SongForge Session 25 — ACE-Step Local Generation")
    print("=" * 60)

    # Initialize DiT handler (no LLM to save VRAM on 6GB card)
    print("\nInitializing ACE-Step DiT handler...")
    dit_handler = AceStepHandler()
    status, success = dit_handler.initialize_service(
        project_root=PROJECT_ROOT,
        config_path="acestep-v15-turbo",
        device="auto",
        use_flash_attention=False,
        compile_model=False,
        offload_to_cpu=True,
        offload_dit_to_cpu=True,
        quantization=None,
    )
    if not success:
        print(f"FAILED: {status}")
        sys.exit(1)
    print(f"DiT ready: {status}")

    llm_handler = LLMHandler()  # Empty handler, no LLM loaded

    config = GenerationConfig(
        batch_size=1,
        audio_format="mp3",
        mp3_bitrate="256k",
    )

    for i, track in enumerate(TRACKS):
        print(f"\n{'='*60}")
        print(f"Track {i+1}/{len(TRACKS)}: {track['name']}")
        print(f"{'='*60}")

        params = GenerationParams(
            task_type="text2music",
            caption=track["caption"],
            lyrics=track["lyrics"],
            duration=track["duration"],
            bpm=track["bpm"],
            keyscale=track["keyscale"],
            seed=track["seed"],
            guidance_scale=7.0,
            inference_steps=8,
            thinking=False,  # No LLM, so no thinking
            use_cot_metas=False,
            use_cot_caption=False,
            use_cot_lyrics=False,
            use_cot_language=False,
        )

        try:
            result = generate_music(
                dit_handler, llm_handler, params, config,
                save_dir=os.path.join(SAVE_DIR, track["name"]),
            )
            print(f"✅ Saved: {track['name']}")
        except Exception as e:
            print(f"❌ Failed: {e}")

    print("\n" + "=" * 60)
    print("Session 25 complete!")
    print(f"Output: {SAVE_DIR}")
    print("=" * 60)

if __name__ == "__main__":
    main()
